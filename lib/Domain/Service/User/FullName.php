namespace Poweradmin\Domain\Service\User;

final class FullName
{
    /**
     * Drops control characters and invisible direction or spacing marks: a line break in
     * a name would reach plain-text mail, the others make two names look alike. ZWNJ, ZWJ
     * and the soft hyphen stay, since several scripts need them.
     */
    public static function plain(string $name): string
    {
        return (string)preg_replace('/[\p{Cc}\x{200B}\x{200E}\x{200F}\x{202A}-\x{202E}\x{2060}\x{2066}-\x{2069}\x{FEFF}]/u', '', mb_scrub($name, 'UTF-8'));
    }
}
